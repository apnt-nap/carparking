// Builds site/data.js (the static demo website's data) from the same sample data the app uses.
// Run: node scripts/build-site-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const malls = JSON.parse(readFileSync('server/data/malls.json', 'utf8')).malls;
const floors = JSON.parse(readFileSync('server/data/floors.json', 'utf8')).floors;

const r = (n) => Math.round(n * 100) / 100;
const out = {
  malls: malls.map((m) => ({
    id: m.id, name_th: m.name_th, name_en: m.name_en, area_th: m.area_th, area_en: m.area_en,
    aliases: m.aliases, lat: m.lat, lng: m.lng, hours: m.hours, fees: m.fees,
  })),
  floors: floors.map((f) => ({
    id: f.id, mall_id: f.mall_id, level: f.level, order: f.order, name_th: f.name_th, name_en: f.name_en,
    plan: {
      width: f.plan.width, height: f.plan.height,
      nodes: f.plan.nodes.map((n) => [n.id, r(n.x), r(n.y)]),
      edges: f.plan.edges.map((e) => [e.from, e.to, e.one_way ? 1 : 0]),
      ramps: f.plan.ramps.map((x) => ({ kind: x.kind, x: x.x, y: x.y, w: x.w, h: x.h, th: x.label_th, en: x.label_en })),
      lobbies: f.plan.lobbies.map((x) => ({ x: x.x, y: x.y, w: x.w, h: x.h, th: x.label_th, en: x.label_en })),
    },
    // [id suffix, zone, x, y, w, h, type, lane node, metres to lift]
    bays: f.bays.map((b) => [b.id.slice(f.id.length + 1), b.zone, r(b.x), r(b.y), r(b.w), r(b.h), b.type[0], b.node, r(b.lift_distance_m)]),
  })),
};

writeFileSync('site/data.js', `// Generated by scripts/build-site-data.mjs from server/data. SAMPLE DATA, made up for the demo.\nwindow.DEMO_DATA = ${JSON.stringify(out)};\n`);
console.log('site/data.js written', out.malls.length, 'malls', out.floors.length, 'floors');
